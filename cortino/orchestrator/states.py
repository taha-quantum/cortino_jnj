from enum import StrEnum


class RunState(StrEnum):
    CREATED = "CREATED"
    INTAKE = "INTAKE"
    PARSED = "PARSED"
    PLANNED = "PLANNED"
    AWAITING_PLAN_APPROVAL = "AWAITING_PLAN_APPROVAL"
    BUILDING = "BUILDING"
    INTEGRATING = "INTEGRATING"
    VERIFYING = "VERIFYING"
    AWAITING_PREVIEW_APPROVAL = "AWAITING_PREVIEW_APPROVAL"
    CHANGES_REQUESTED = "CHANGES_REQUESTED"
    PR_OPEN = "PR_OPEN"
    NEEDS_INPUT = "NEEDS_INPUT"
    REJECTED = "REJECTED"
    FAILED = "FAILED"


class IllegalTransition(Exception):
    pass


S = RunState
END_STATES = {S.PR_OPEN, S.REJECTED, S.FAILED}

_EDGES: dict[RunState, set[RunState]] = {
    S.CREATED: {S.INTAKE},
    S.INTAKE: {S.PARSED, S.NEEDS_INPUT},
    S.PARSED: {S.PLANNED},
    S.PLANNED: {S.AWAITING_PLAN_APPROVAL, S.BUILDING},
    S.AWAITING_PLAN_APPROVAL: {S.BUILDING, S.PLANNED, S.REJECTED},
    S.BUILDING: {S.INTEGRATING},
    S.INTEGRATING: {S.VERIFYING, S.BUILDING},
    S.VERIFYING: {S.AWAITING_PREVIEW_APPROVAL, S.BUILDING, S.NEEDS_INPUT},
    S.AWAITING_PREVIEW_APPROVAL: {S.PR_OPEN, S.CHANGES_REQUESTED, S.REJECTED},
    S.CHANGES_REQUESTED: {S.PLANNED},
    # NEEDS_INPUT -> origin state is checked by RunStore against meta["resume_to"].
    S.NEEDS_INPUT: {S.INTAKE, S.VERIFYING, S.BUILDING},
    S.PR_OPEN: set(),
    S.REJECTED: set(),
    S.FAILED: set(),
}

TRANSITIONS: dict[RunState, set[RunState]] = {
    s: (to if s in END_STATES else to | {S.FAILED}) for s, to in _EDGES.items()
}
